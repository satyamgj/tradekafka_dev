package com.finmamba.models.request;

import com.fasterxml.jackson.annotation.JsonProperty;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;

/**
 * 
 * @author Swanand
 * Model for user profile details like realmName, realmId, clientId, clientName, userGroupId, userGroupName
 *
 */

@Data
@AllArgsConstructor
@NoArgsConstructor
@Builder
@ToString
public class UserProfileModel {
	
	@JsonProperty(value = "realmId")
	private String realmId;
	@JsonProperty(value = "realmName")
	private String realmName;
	@JsonProperty(value = "clientId")
	private String clientId;
	@JsonProperty(value = "clientName")
	private String clientName;
	@JsonProperty(value = "groupId")
	private String groupId;
	@JsonProperty(value = "groupName")
	private String groupName;
	@JsonProperty(value = "clientRoleName")
	private String clientRoleName;
	@JsonProperty(value = "realmRole")
	private String realmRole;
	/*
	 * user id generated by the identity provider
	 */
	@JsonProperty(value = "idpUserId")
	private String idpUserId; 
}
